static const uint8_t roam_font_dash[7]  = {0,0,0,0x1F,0,0,0};
static const uint8_t roam_font_under[7] = {0,0,0,0,0,0,0x1F};
static const uint8_t roam_font_dot[7]   = {0,0,0,0,0,0x0C,0x0C};
static const uint8_t roam_font_q[7]     = {0x0E,0x11,0x01,0x02,0x04,0,0x04};

static const uint8_t *roam_glyph(char c)
{
    static const uint8_t blank[7] = {0};
    if (c >= 'a' && c <= 'z') c = (char)(c - 32);
    if (c >= 'A' && c <= 'Z') return roam_font_az[c - 'A'];
    if (c >= '0' && c <= '9') return roam_font_09[c - '0'];
    if (c == '-') return roam_font_dash;
    if (c == '_') return roam_font_under;
    if (c == '.') return roam_font_dot;
    if (c == ' ') return blank;
    return roam_font_q;
}

/* Rectangles for `s` with its top-left at (x, y), each font pixel `px`
 * screen pixels; `pad` grows each rect (an outline pass uses pad = 1).
 * Calls emit(l, t, r, b, ctx) per lit font pixel. Text is 6*px per char wide. */
static void roam_text_rects(const char *s, int x, int y, int px, int pad,
                            void (*emit)(int, int, int, int, void *), void *ctx)
{
    int i, row, col;
    for (i = 0; s[i]; i++) {
        const uint8_t *g = roam_glyph(s[i]);
        for (row = 0; row < 7; row++)
            for (col = 0; col < 5; col++)
                if (g[row] & (0x10 >> col)) {
                    int l = x + (i * 6 + col) * px, t = y + row * px;
                    emit(l - pad, t - pad, l + px + pad, t + px + pad, ctx);
                }
    }
}
