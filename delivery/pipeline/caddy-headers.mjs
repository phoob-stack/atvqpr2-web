// caddy-headers.mjs - the site's _headers file (Cloudflare Pages / Netlify
// format) as a Caddy snippet, so the site keeps exactly its own headers (its
// CSP with the inline-script hash, COOP/COEP) when Caddy serves it.
//
//   /*
//     Header-Name: value
// becomes
//   header /* Header-Name "value"
// (an inline path matcher, so the snippet can be imported inside a handle block)
export function headersToCaddy(text) {
  const out = ['# Generated by pipeline/build.mjs from the site\'s _headers. Do not edit.'];
  let path = null;
  for (const raw of text.split(/\r?\n/)) {
    if (!raw.trim() || raw.trim().startsWith('#')) continue;
    if (!/^\s/.test(raw)) {
      path = raw.trim();
      if (!/^\/[\w\-./*]*$/.test(path)) throw new Error(`_headers: unsupported path ${path}`);
      continue;
    }
    if (!path) throw new Error('_headers: a header before any path');
    const m = /^\s+([A-Za-z0-9-]+):\s*(.*)$/.exec(raw);
    if (!m) throw new Error(`_headers: cannot read ${raw.trim()}`);
    out.push(`header ${path} ${m[1]} "${m[2].replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`);
  }
  return out.join('\n') + '\n';
}
